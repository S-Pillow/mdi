class TestUploadParserHeaderRow:
    def test_csv_skips_comment_rows_finds_header(self):
        csv = (
            "# comment row\n"
            "# filter\n"
            "DNS Form,Create Date,EPP Status\n"
            "good.com,2020-01-01,clientTransferProhibited\n"
        ).encode()
        result = parse_upload(csv, "comments.csv")
        assert result.header_row == 3
        assert len(result.accepted) == 1
        assert result.accepted[0].input_normalized == "good.com"

    def test_internal_export_xlsx_shape(self):
        xlsx = _internal_export_xlsx()
        result = parse_upload(xlsx, "test.xlsx")
        assert result.header_row == 5
        assert result.source_sheet == "Sheet"
        assert len(result.accepted) == 17
        assert result.columns_detected.domain == "DNS Form"
        assert result.columns_detected.created_at == "Create Date"
        assert result.columns_detected.epp_status == "EPP Status"
        assert result.columns_detected.domain_state == "Domain State"
        assert result.columns_detected.registrar == "Registrar Name"
        assert result.columns_detected.nameservers == "Assigned Nameservers"
        held = [i for i in result.accepted if i.input_normalized == "stanley-quencher.us"]
        assert len(held) == 1
        assert held[0].domain_hold.has_hold is True
        assert DomainHoldType.CLIENT_HOLD in held[0].domain_hold.hold_types
        assert held[0].created_at == "2021-03-10"
        assert held[0].registrar == "Reg C"
        assert "ns1.c.com" in held[0].assigned_nameservers

    def test_domain_state_only_detects_hold(self):
        csv = (
            "Domain,Domain State\n"
            "held.example.com,clientHold\n"
        ).encode()
        result = parse_upload(csv, "state_only.csv")
        assert len(result.accepted) == 1
        assert result.accepted[0].domain_hold.has_hold is True

    def test_legacy_xls_unsupported(self):
        result = parse_upload(b"fake", "legacy.xls")
        assert len(result.accepted) == 0
        assert result.rejected[0].error.code == "unsupported_format"


class TestUploadEstimateSubmit:
    def _upload_items(self):
        xlsx = _internal_export_xlsx()
        result = parse_upload(xlsx, "test.xlsx")
        return result.accepted

    def test_upload_estimate_excludes_held_from_vt_count(self):
        items = self._upload_items()
        resp = client.post("/api/mdi/jobs/estimate", json={
            "items": [i.model_dump(mode="json") for i in items],
            "input_mode": "upload",
            "use_domain_reports": False,
        })
        assert resp.status_code == 200, resp.text
        body = resp.json()
        assert body["accepted_count"] == 17
        assert body["held_skipped_count"] == 1
        assert body["eligible_vt_count"] == 16

    def test_upload_submit_preserves_metadata_and_skips_held_vt(self, tmp_path):
        items = _small_upload_items()
        held = next(i for i in items if i.input_normalized == "stanley-quencher.us")
        job_store.clear_all_jobs()

        resp = client.post("/api/mdi/jobs/submit", json={
            "items": [i.model_dump(mode="json") for i in items],
            "input_mode": "upload",
            "use_domain_reports": False,
        })
        assert resp.status_code == 200, resp.text
        data = resp.json()
        assert data["held_skipped_count"] == 1
        assert data["total"] == 1
        job_id = data["job_id"]

        usage_file = tmp_path / "vt_usage.json"
        usage_file.write_text('{"date_utc": "2099-01-01", "daily_lookups_used": 0}')
        job_file = tmp_path / "mdi_latest_job.json"

        with (
            patch("services.vt_service._vt_request", new=AsyncMock(return_value=_mock_resp(200, _vt_clean_body()))),
            patch.dict(os.environ, {"VT_API_KEY": "testkey"}),
        ):
            _run(job_processor.process_job(
                job_id,
                usage_file=usage_file,
                job_file=job_file,
                history_file=tmp_path / "vt_usage_history.jsonl",
                daily_file=tmp_path / "vt_daily_history.json",
            ))

        job = job_store.get_job_sync(job_id)
        held_result = job.results["stanley-quencher.us"]
        assert held_result.processing_status == MdiProcessingStatus.HOLD_SKIPPED
        assert held_result.vt_mode_used == VtModeUsed.SKIPPED_HOLD
        assert held_result.registrar == held.registrar
        assert held_result.domain_hold.has_hold is True
        assert held_result.domain_hold.source == DomainStatusSource.UPLOADED_FILE
        assert job.lookups_used == 1

    def test_upload_preview_quota_free(self):
        xlsx = _internal_export_xlsx()
        resp = client.post(
            "/api/mdi/jobs/upload-preview",
            files={"file": ("test.xlsx", xlsx, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")},
            data={"default_scheme": "http"},
        )
        assert resp.status_code == 200
        body = resp.json()
        assert body["accepted_count"] == 17
        assert body["held_count"] == 1
        assert body["header_row"] == 5
        assert body["quota_consumed"] is False
        assert body["external_calls_made"] is False
