def _make_noop_enrichment(registered_domain: str = "example.com") -> EnrichmentResult:
    return EnrichmentResult(
        registered_domain=registered_domain,
        source=DomainStatusSource.NOT_CHECKED,
        domain_hold=DomainHold(
            has_hold=False,
            hold_types=[DomainHoldType.NONE],
            source=DomainStatusSource.NOT_CHECKED,
        ),
    )


def _mock_resp(status_code: int, body: dict = None) -> MagicMock:
    m = MagicMock()
    m.status_code = status_code
    m.json.return_value = body or {}
    return m


def _vt_clean_body():
    return {
        "data": {"attributes": {
            "last_analysis_stats": {"malicious": 0, "suspicious": 0, "harmless": 70, "undetected": 5, "timeout": 0},
            "last_analysis_date": int(time.time()) - 3600,
        }}
    }


def _xlsx_bytes(rows: list[list]) -> bytes:
    wb = openpyxl.Workbook()
    ws = wb.active
    for row in rows:
        ws.append(row)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _internal_export_xlsx() -> bytes:
    """Representative internal export: 4 comment rows, header row 5, 17 domains, 1 held."""
    rows = [
        ["# Export generated by internal tool"],
        ["# Filter: active domains"],
        ["# Do not edit header row"],
        ["#"],
        [
            "DNS Form", "Create Date", "EPP Status", "Domain State",
            "Registrar Name", "Assigned Nameservers",
            "Registrant Name", "Registrant Email",
        ],
    ]
    domains = [
        ("example-one.com", "2020-01-15", "clientTransferProhibited", "ok", "Reg A", "ns1.a.com"),
        ("example-two.com", "2019-06-01", "clientTransferProhibited", "ok", "Reg B", "ns1.b.com"),
        ("stanley-quencher.us", "2021-03-10", "clientHold", "clientHold", "Reg C", "ns1.c.com"),
    ]
    for i in range(4, 18):
        domains.append((
            f"domain-{i}.com",
            "2022-01-01",
            "clientTransferProhibited",
            "ok",
            f"Reg {i}",
            f"ns1.d{i}.com",
        ))
    for d in domains:
        rows.append([d[0], d[1], d[2], d[3], d[4], d[5], "Contact Person", "contact@example.com"])
    return _xlsx_bytes(rows)


